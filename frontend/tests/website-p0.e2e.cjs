async function actor() {
  const context = await browser.newContext({viewport:{width:1440,height:1000}}), page = await context.newPage()
  page.on('pageerror',e=>errors.push(e.message))
  return {context,page}
}
async function api(actor,method,url,body,expected=200) {
  let headers = {Origin:origin}
  if(method!=='GET') {
    const me=await actor.context.request.get(origin+'/api/v1/auth/me')
    assert.equal(me.status(),200,'Actor must be authenticated')
    headers['X-CSRF-Token']=(await me.json()).csrf_token
  }
  const response=await actor.context.request.fetch(origin+'/api/v1'+url,{method,headers,data:body})
  assert.equal(response.status(),expected,`${method} ${url} -> ${response.status()}`)
  return response.status()===204?null:response.json()
}
async function login(actor,email,pw,next) {
  await actor.page.goto(origin+'/login'+(next?'?next='+encodeURIComponent(next):''),{waitUntil:'networkidle'})
  await actor.page.getByLabel('Email',{exact:true}).fill(email)
  await actor.page.getByLabel('Mật khẩu',{exact:true}).fill(pw)
  await actor.page.getByRole('button',{name:'Đăng nhập',exact:true}).click()
  await actor.page.locator('.site-header').getByRole('button',{name:'Đăng xuất',exact:true}).waitFor()
}
async function shot(page,name) {
  await fs.mkdir(output,{recursive:true})
  await page.screenshot({path:path.join(output,name),fullPage:true})
}
async function enrollSettings(runId,mode,capacity=1) {
  const settings=await api(teacher,'GET',`/teaching/runs/${runId}/admissions`)
  return api(teacher,'PATCH',`/teaching/runs/${runId}/admissions`,{enrollment_mode:mode,listed:true,opens_at:null,closes_at:null,capacity,expected_revision:settings.admissions_revision})
}

